# join - 합치기 (리스트 -> 문자열)
# 형식 : 'rnqnswk'. joim(리스트) (구분자가 앞에옴)
print('-'.join(['2025','01','15'])) # 2025-01-15

#  split + join
# - split : 문자열 -> 리스트
# - join : 리스트 -> 문자열
raw = '사과, 배, 감'
p = raw.split(',')                                        # '사과', ' 배', ' 감']
print(p)
print('/'.join(p))                                        # 사과/ 배/ 감
print('/'.join([p[0].strip(),p[1].strip(),p[2].strip()])) # 사과/배/감

